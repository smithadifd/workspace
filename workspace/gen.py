"""gen: render the map, the CLAUDE.md pointer, the settings and the per-host workspace file.

From `registry.yaml`, `gen` renders, in the workspace folder:

- `AGENTS.md`, the map: one line per project, with its outgoing edges as
  `uses:` on that line, plus two keep blocks copied from the current map;
- `CLAUDE.md`, exactly `@AGENTS.md`;
- `.claude/settings.json`, where it owns only the code roots in
  `permissions.additionalDirectories` and a Read and an Edit deny rule for every
  excluded path (and, when the person declared a `sandbox` block, each excluded
  path in `sandbox.filesystem.denyRead`), and, only while `registry.yaml` says
  `session_prompt: on`, one `hooks.SessionStart` entry that runs the constant
  command `workspace prompt` (see `HOOK_COMMAND`); every other key, and every
  hook it did not add, passes through;
- `<host>.code-workspace`, the host's folders for an editor;
- `.workspace-gen.json` and `state/gen-<host>.json`, its own manifests.

Without `--write` it prints the plan and a plan hash and writes nothing. With
`--write --expect HASH` it recomputes the plan and writes it only when the hash
matches. Every refusal is decided before the first write, and what it writes
always passes `check`: it runs `check` on the rendered map and settings first.
It runs no other program and opens no network connection.

The write path keeps one rule, for `gen`, `register` and `decline` alike:

- WORKSPACE itself resolves as typed. Below it, every file a verb reads or
  replaces, `registry.yaml` included, is opened once, by its folder's
  descriptor, with O_NOFOLLOW and O_NONBLOCK, and must fstat as a regular
  file. A symlink, folder, FIFO or other special file is refused with exit 1,
  naming it, before any write. Every folder below WORKSPACE is opened without
  following a symlink, and `.claude` and `state` are refused when either is a
  symlink, before anything is read through them.
- That one descriptor gives the file's bytes, identity and mode (a
  `scan.Snapshot`), and the mode of what is written comes only from it: an
  output is never more permissive than the file it replaces, or than its
  keep-block source (a new `AGENTS.md` whose keep blocks come from `CLAUDE.md`
  takes `CLAUDE.md`'s mode). A file with neither gets the usual mode under the
  umask. New bytes go to a temp file only its owner can read, which takes that
  mode before it is renamed into place.
- Just before each rename the name is looked up once more, without following
  a symlink, and read once more through an O_NOFOLLOW descriptor: it must
  still be the regular file that was read, with the same bytes, identity and
  mode, or still be absent. So an edit in place, which keeps the inode and the
  mode, is refused too. This recheck only detects a change; the guard is the
  O_NOFOLLOW open. The byte recheck narrows the window between it and the
  rename; that window was there before the recheck too, and is accepted: a
  rename replaces the folder entry and never writes through a symlink, and the
  folder is a held descriptor, so a concurrent writer in that window cannot
  redirect the write or bring in other bytes. Only a concurrent edit by the
  same user can hit it, and it can only lose its own change to that file; the
  recheck at the confirm (here) and the registry lock (`register`) bound that.
- Stored text is raw, and each sink encodes it for itself: an edge's evidence
  is stored as the real path, quoted for YAML when written, and escaped for
  the terminal only when printed.

Exit codes: 0 planned or written, 1 refused, 2 could not verify.
"""
