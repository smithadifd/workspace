def keep_blocks(text, label):
    """{name: content} for the keep blocks in `text`, and whether it holds any marker."""
    blocks = {}
    current = None
    content = []
    marked = False
    for number, line in enumerate(text.splitlines(keepends=True), 1):
        bare = line.rstrip("\r\n")
        if KEEP_WORD in bare:
            marked = True
            match = KEEP_MARKER.match(bare)
            where = "%s line %d" % (label, number)
            if not match:
                raise Refusal("%s: malformed keep marker (write `<!-- workspace:keep begin top "
                              "-->` and `<!-- workspace:keep end top -->`)" % where)
            action, name = match.groups()
            if name not in KEEP_NAMES:
                raise Refusal("%s: unknown keep block `%s` (the names are top and bottom)"
                              % (where, name))
            if action == "begin":
                if current is not None:
                    raise Refusal("%s: keep block `%s` begins inside `%s`" % (where, name, current))
                if name in blocks:
                    raise Refusal("%s: keep block `%s` appears twice" % (where, name))
                current = name
                content = []
            else:
                if current is None:
                    raise Refusal("%s: keep block `%s` ends without a begin" % (where, name))
                if name != current:
                    raise Refusal("%s: `end %s` closes `begin %s`" % (where, name, current))
                blocks[current] = "".join(content)
                current = None
            continue
        if current is not None:
            content.append(line)
    if current is not None:
        raise Refusal("%s: keep block `%s` has no end marker" % (label, current))
    return blocks, marked


def blank_keep(text):
    """`text` with every keep block's content removed: the gen-owned part of the map."""
    out = []
    inside = False
    for line in text.splitlines(keepends=True):
        match = KEEP_MARKER.match(line.rstrip("\r\n"))
        if match:
            inside = match.group(1) == "begin"
            out.append(line)
            continue
        if not inside:
            out.append(line)
    return "".join(out)


def keep_section(name, content):
    if content and not content.endswith("\n"):
        content += "\n"
    return ("<!-- workspace:keep begin %s -->\n%s<!-- workspace:keep end %s -->\n"
            % (name, content, name))


