class Plan:
    def __init__(self):
        self.targets = []
        self.manifest = None
        self.state = None
        self.manifest_text = None
        self.state_text = None
        self.pending_manifest = None
        self.pending_state = None
        self.lines = []
        self.digest = None
        self.host = None


def manifest_text(manifest):
    return json.dumps(manifest, indent=2, sort_keys=True) + "\n"


def read_manifest(workspace, rel):
    snapshot = read_snapshot(workspace, rel)
    if snapshot is None:
        return None, {"version": MANIFEST_VERSION, "files": {}}
    manifest = load_json(snapshot.data, rel)
    if manifest.get("version") != MANIFEST_VERSION or not isinstance(manifest.get("files"), dict):
        raise scan.Unverifiable("%s is not a gen manifest this version reads" % rel)
    return snapshot, manifest


def make_plan(workspace, host_flag, adopt):
    plan = Plan()
    registry = scan.registry_snapshot(workspace)
    document = scan.parse_registry(registry.data)
    session_prompt, session_note = scan.session_prompt(registry.data)
    code_roots, excluded, _, _ = scan.validate(document)
    host = scan.select_host(code_roots, host_flag)
    plan.host = host
    clusters = map_gate(document, code_roots)
    exclusions = [scan.exclusion_pattern(path) for path in excluded]
    path_gate(document, exclusions)
    literal_gate(excluded)
    output_folder_gate(workspace)

    state_rel = os.path.join(STATE_DIR, "gen-%s.json" % host)
    workspace_rel = "%s.code-workspace" % host
    manifest_snapshot, manifest = read_manifest(workspace, MANIFEST_NAME)
    state_snapshot, state = read_manifest(workspace, state_rel)
    files = manifest["files"]
    state_files = state["files"]

    agents_snapshot = read_snapshot(workspace, MAP_NAME)
    shim_snapshot = read_snapshot(workspace, SHIM_NAME)
    agents = None if agents_snapshot is None else agents_snapshot.data
    shim = None if shim_snapshot is None else shim_snapshot.data
    # The keep blocks' source; a new map takes its mode, so copied bytes keep it.
    if agents is not None:
        keep_source, source, source_snapshot = MAP_NAME, agents, agents_snapshot
    elif shim is not None and shim != SHIM_TEXT.encode("utf-8"):
        keep_source, source, source_snapshot = SHIM_NAME, shim, shim_snapshot
    else:
        keep_source, source, source_snapshot = None, None, None
    if source is None:
        keep, marked = {}, False
        recorded = manifest.get("keep") or {}
        for name in KEEP_NAMES:
            if recorded.get(name) not in (None, sha256("")):
                raise Refusal(KEEP_SOURCE_MISSING % name)
    else:
        keep, marked = keep_blocks(decode(source, keep_source), keep_source)

    map_text = render_map(document, clusters, keep)
    budget_gate(map_text)
    import_gate(map_text, document, workspace)

    settings_snapshot = read_snapshot(workspace, SETTINGS_REL)
    settings_data = None if settings_snapshot is None else settings_snapshot.data
    existing = {} if settings_data is None else load_json(settings_data, SETTINGS_REL)
    settings_lists(existing, create=False)
    entry = files.get(SETTINGS_REL)
    owned_before = (entry or {}).get("owned") or empty_owned()
    adopting = adopt or entry is None
    merged, owned_after = merge_settings(existing, code_roots, excluded, owned_before, adopting,
                                         session_prompt)
    if settings_data is not None and merged == existing:
        settings_render = settings_data
    else:
        settings_render = settings_text(merged).encode("utf-8")

    gaps = check.check(document, map_text, merged)
    if gaps:
        raise Refusal(*["gen output fails check: %s" % gap for gap in gaps])

    plan.targets = [
        Target(MAP_NAME, agents_snapshot, map_text.encode("utf-8"), "map",
               mode=None if source_snapshot is None else source_snapshot.mode),
        Target(SHIM_NAME, shim_snapshot, SHIM_TEXT.encode("utf-8"), "shim"),
        Target(SETTINGS_REL, settings_snapshot, settings_render, "settings",
               owned_before, owned_after),
        Target(workspace_rel, read_snapshot(workspace, workspace_rel),
               render_code_workspace(document, host).encode("utf-8"), "code-workspace"),
    ]
    reasons = []
    for target in plan.targets:
        records = state_files if target.kind == "code-workspace" else files
        try:
            judge(target, records.get(target.rel), adopt, keep_source, marked)
        except Refusal as refusal:
            reasons.extend(refusal.reasons)
    if reasons:
        raise Refusal(*reasons)

    # The manifests: the final record, and the pending record written before any target.
    final = {"version": MANIFEST_VERSION, "files": {},
             "keep": {name: sha256(keep.get(name, "")) for name in KEEP_NAMES}}
    final_state = {"version": MANIFEST_VERSION, "files": {}}
    pending = copy.deepcopy(manifest)
    pending_state = copy.deepcopy(state)
    for target in plan.targets:
        new_hash = target.owned_hash(target.render, target.owned_after)
        record = {"hash": new_hash}
        if target.kind == "settings":
            record["owned"] = target.owned_after
        holder, pending_holder = ((final_state, pending_state) if target.kind == "code-workspace"
                                  else (final, pending))
        holder["files"][target.rel] = record
        old = pending_holder["files"].get(target.rel)
        if old is None:
            # First adoption: record the pre-write hash before the file is replaced,
            # so a retry after an interruption still matches the original file.
            old = {"hash": target.owned_hash(target.current, target.owned_after)}
            if target.kind == "settings":
                old["owned"] = target.owned_after
            if old["hash"] is None:
                del old["hash"]
        old = dict(old)
        old["pending"] = new_hash
        if target.kind == "settings":
            old["pending_owned"] = target.owned_after
        pending_holder["files"][target.rel] = old
    plan.manifest_text = manifest_text(final).encode("utf-8")
    plan.state_text = manifest_text(final_state).encode("utf-8")
    plan.pending_manifest = manifest_text(pending).encode("utf-8")
    plan.pending_state = manifest_text(pending_state).encode("utf-8")
    plan.manifest_snapshot = manifest_snapshot
    plan.state_snapshot = state_snapshot
    plan.manifest_data = None if manifest_snapshot is None else manifest_snapshot.data
    plan.state_data = None if state_snapshot is None else state_snapshot.data
    plan.state_rel = state_rel

    planned = {target.rel: target.render for target in plan.targets}
    planned[MANIFEST_NAME] = plan.manifest_text
    planned[state_rel] = plan.state_text
    plan.digest = plan_digest("gen", [("host", host_flag), ("adopt", bool(adopt))], planned)

    lines = [] if session_note is None else ["note   %s" % session_note]
    for target in plan.targets:
        if not target.changes:
            lines.append("same   %s" % target.rel)
            continue
        if target.kind == "settings":
            lines.append("change %s (gen-owned entries only):" % target.rel)
            lines.extend(settings_plan_lines(owned_view_lists(existing, owned_before),
                                             owned_view_lists(merged, owned_after)))
            continue
        lines.append(("new    %s" if target.current is None else "change %s") % target.rel)
        lines.append(unified(None if target.current is None
                             else target.current.decode("utf-8", "replace"),
                             target.render.decode("utf-8"), target.rel).rstrip("\n"))
    if plan.manifest_text != plan.manifest_data:
        lines.append("record %s" % MANIFEST_NAME)
    if plan.state_text != plan.state_data:
        lines.append("record %s" % state_rel)
    plan.lines = lines
    return plan


def owned_view_lists(settings, owned):
    lists = settings_lists(copy.deepcopy(settings), create=False)
    view = {key: [item for item in (lists.get(key) or []) if item in owned.get(key, [])]
            for key in empty_owned()}
    view[HOOK_KEY] = hook_present(settings, owned)
    return view


