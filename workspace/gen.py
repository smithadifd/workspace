class Target:
    """One file gen owns: its current snapshot, its render, and how its owned part is hashed.

    `mode` is the mode the render is written with: the snapshot's, or None for
    the usual mode of a new file.
    """

    def __init__(self, rel, snapshot, render, kind, owned_before=None, owned_after=None,
                 mode=None):
        self.rel = rel
        self.snapshot = snapshot
        self.current = None if snapshot is None else snapshot.data
        self.mode = snapshot.mode if snapshot is not None else mode
        self.render = render
        self.kind = kind
        self.owned_before = owned_before
        self.owned_after = owned_after

    def owned_hash(self, data, owned=None):
        if data is None:
            return None
        if self.kind == "map":
            return sha256(blank_keep(data.decode("utf-8")))
        if self.kind == "settings":
            return sha256(settings_view(json.loads(data.decode("utf-8")), owned or {}))
        return sha256(data)

    @property
    def changes(self):
        return self.current != self.render


def adoption_detail(target):
    """What adopting would change: the diff, or for the settings only gen-owned entries.

    The settings file can hold the person's credentials (`env`, `apiKeyHelper`),
    so no line of it outside gen's own entries is ever printed.
    """
    if target.kind == "settings":
        owned = target.owned_after
        before = owned_view_lists(json.loads(target.current.decode("utf-8")), owned)
        after = owned_view_lists(json.loads(target.render.decode("utf-8")), owned)
        return "\n".join(["(gen-owned entries only)"] + settings_plan_lines(before, after))
    return unified(target.current.decode("utf-8", "replace"), target.render.decode("utf-8"),
                   target.rel)


def judge(target, entry, adopt, keep_source, keep_marked):
    """Refuse a diverged or unadoptable target (G8, G9); return nothing when it may be written."""
    if target.current is None:
        return
    render_hash = target.owned_hash(target.render, target.owned_after)
    if entry is None:
        if target.owned_hash(target.current, target.owned_after) == render_hash:
            return
        if not adopt:
            raise Refusal("%s exists and gen has no record of writing it; check the plan's diff "
                          "and rerun with --adopt to replace it\n%s"
                          % (target.rel, adoption_detail(target)))
        if target.current.decode("utf-8", "replace").startswith(HEADER_PREFIX):
            raise Refusal("%s carries a GENERATED header but gen has no record of writing it; "
                          "--adopt replaces only a hand-kept file" % target.rel)
        if target.kind in ("map", "shim") and (target.rel != keep_source or not keep_marked):
            raise Refusal(NEEDS_KEEP % target.rel)
        return
    if target.owned_hash(target.current, entry.get("owned")) == entry.get("hash"):
        return
    if "pending" in entry and (target.owned_hash(target.current, entry.get("pending_owned"))
                               == entry["pending"]):
        return
    if target.owned_hash(target.current, target.owned_after) == render_hash:
        return
    detail = ""
    if target.kind == "settings":
        missing = []
        current = json.loads(target.current.decode("utf-8"))
        present = owned_view_lists(current, entry.get("owned") or {})
        for key, items in (entry.get("owned") or {}).items():
            for item in items:
                if item not in present.get(key, []):
                    missing.append("%s %s" % (key, item))
        if missing:
            detail = "\ngen-owned entries removed by hand: " + ", ".join(missing)
    else:
        detail = "\n" + unified(target.current.decode("utf-8", "replace"),
                                target.render.decode("utf-8"), target.rel)
    raise Refusal("%s was changed outside gen (it matches neither gen's record nor the "
                  "render); restore it or move the change into registry.yaml%s"
                  % (target.rel, detail))


