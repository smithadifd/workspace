def cluster_ids(value):
    if value is None:
        return []
    if isinstance(value, str) and value:
        return [value]
    if isinstance(value, list) and value and all(isinstance(item, str) and item
                                                 for item in value):
        return list(value)
    return None


def single_line(text):
    return "\n" not in text and "\r" not in text


def map_gate(document, code_roots):
    """Refuse a registry the map grammar cannot carry, naming every entry."""
    reasons = []
    for host in code_roots:
        if not HOST_FILE_NAME.match(host):
            reasons.append("code_roots host `%s` is not a plain file name; gen writes "
                           "<host>.code-workspace and state/gen-<host>.json" % host)
    clusters = {}
    for cluster in document.get("clusters") or []:
        cluster_id = cluster.get("id")
        if not isinstance(cluster_id, str) or not cluster_id:
            reasons.append("a cluster has no id")
            continue
        if cluster_id in clusters:
            reasons.append("cluster id `%s` is repeated" % cluster_id)
            continue
        clusters[cluster_id] = cluster
        name = cluster_name(cluster)
        if "*" in name:
            reasons.append("cluster `%s` name holds `*`, which the map heading cannot carry"
                           % cluster_id)
        one_liner = cluster.get("one_liner")
        if one_liner is not None and (not isinstance(one_liner, str)
                                      or not single_line(one_liner)):
            reasons.append("cluster `%s` one_liner must be one line of text" % cluster_id)
    seen = set()
    for project in document.get("projects") or []:
        name = project.get("name")
        if name in seen:
            reasons.append("project name `%s` is used twice" % name)
        seen.add(name)
        if "`" in name:
            reasons.append("project name %r holds a backtick, which the map line cannot carry"
                           % name)
        ids = cluster_ids(project.get("cluster"))
        if ids is None:
            reasons.append("project `%s` cluster must be a cluster id or a list of ids" % name)
            continue
        for cluster_id in ids:
            if cluster_id not in clusters:
                reasons.append("project `%s` names cluster `%s`, which is not in clusters"
                               % (name, cluster_id))
            elif (clusters[cluster_id].get("lifecycle") == "archived"
                  and project.get("lifecycle") != "archived"):
                reasons.append("project `%s` is %s but its cluster `%s` is archived"
                               % (name, project.get("lifecycle"), cluster_id))
        one_liner = project.get("one_liner")
        if one_liner is None:
            continue
        if not isinstance(one_liner, str) or not single_line(one_liner):
            reasons.append("project `%s` one_liner must be one line of text" % name)
        elif len(one_liner) > ONE_LINER_LIMIT:
            reasons.append("project `%s` one_liner is %d characters, over the limit of %d"
                           % (name, len(one_liner), ONE_LINER_LIMIT))
    if reasons:
        raise Refusal(*reasons)
    return clusters


def cluster_name(cluster):
    name = cluster.get("name")
    return name if isinstance(name, str) and name else cluster.get("id")


def path_gate(document, exclusions):
    """Refuse a project path under an excluded path, on any host (lexical)."""
    reasons = []
    for project in document.get("projects") or []:
        for host, text in (project.get("paths") or {}).items():
            path = scan.expand_path(text, "project `%s` path" % project["name"])
            if scan.is_excluded(path, exclusions):
                reasons.append("project `%s` path %s (host `%s`) is under an excluded path"
                               % (project["name"], text, host))
    if reasons:
        raise Refusal(*reasons)


def literal_gate(excluded):
    """An excluded entry whose real name holds a glob character no deny rule can match literally.

    `scan` excludes such an entry by its literal text, but a deny rule reads
    `[`, `*` and `?` as a pattern. When the literal entry exists and the
    pattern does not match its own text, no rule gen can write (and `check`
    accepts) denies it, so gen cannot verify the settings it would write.
    """
    for text in excluded:
        literal = scan.exclusion_pattern(text)
        if not any(character in literal for character in GLOB_CHARACTERS):
            continue
        try:
            os.lstat(literal)
        except OSError:
            continue
        if not fnmatch.fnmatchcase(literal, literal):
            raise scan.Unverifiable(
                "excluded path `%s` names the entry %s, whose real name holds a glob character "
                "that a deny rule reads as a pattern; no deny rule gen can write matches it, so "
                "it is not denied (rename it, or exclude the folder above it)" % (text, literal))


