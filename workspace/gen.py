def temp_path(path):
    folder, name = os.path.split(path)
    return os.path.join(folder, "." + name + TEMP_SUFFIX)


def remove_leftover_temps(workspace):
    for rel in ("",) + OUTPUT_FOLDERS:
        try:
            handle = open_folder(workspace, rel)
        except OSError:
            continue
        try:
            for name in os.listdir(handle):
                if TEMP_NAME.match(name):
                    os.unlink(name, dir_fd=handle)
        except OSError:
            continue
        finally:
            os.close(handle)


class TargetChanged(OSError):
    """A file is no longer the one the plan read, just before its rename."""


def write_temp(folder, name, data, mode):
    """Write `data` to a new temp beside `name` in the folder descriptor `folder`.

    `mode` comes only from the snapshot of the file it replaces, or of its
    keep-block source: the temp is created readable by its owner only and
    given that mode once written, so it is never more permissive than its
    source. With no source (`mode` None) it gets the usual mode under the umask.
    Returns the temp's name and its (node, mode).
    """
    temp = temp_path(name)
    handle = os.open(temp, TEMP_FLAGS, 0o666 if mode is None else 0o600, dir_fd=folder)
    with os.fdopen(handle, "wb") as stream:
        stream.write(data)
        stream.flush()
        if mode is not None:
            os.fchmod(stream.fileno(), mode)
        os.fsync(stream.fileno())
        info = os.fstat(stream.fileno())
    return temp, (scan.node_of(info), stat.S_IMODE(info.st_mode))


def require_unchanged(folder, name, expected, rel):
    """Refuse unless `name` is still the file `expected` (node, mode, bytes) names, or absent.

    Detection only, just before a rename; the O_NOFOLLOW read is the guard.
    The name is looked up without following a symlink, then read once more
    through one O_NOFOLLOW descriptor, so a file edited in place (same inode,
    same mode) is refused as well as one replaced.
    """
    now = scan.entry_identity(folder, name)
    if expected is None:
        same = now is None
    else:
        node, mode, data = expected
        same = now is not None and now[2] and (now[0], now[1]) == (node, mode)
        if same:
            try:
                again = scan.snapshot_at(folder, name, rel)
            except scan.Unverifiable:
                again = None
            same = (again is not None and again.identity == (node, mode)
                    and again.data == data)
    if not same:
        raise TargetChanged("%s changed since the plan read it" % rel)


def write_atomic(folder, name, data, expected, rel=None):
    """Replace `name` in the folder descriptor `folder` atomically.

    `expected` is the (node, mode, bytes) of the snapshot it replaces, or None
    for a new file; the new file takes that mode. Returns the new file's
    (node, mode, bytes).
    """
    temp, identity = write_temp(folder, name, data, None if expected is None else expected[1])
    try:
        require_unchanged(folder, name, expected, rel or name)
        os.replace(temp, name, src_dir_fd=folder, dst_dir_fd=folder)
    except BaseException:
        try:
            os.unlink(temp, dir_fd=folder)
        except OSError:
            pass
        raise
    return identity + (data,)


def expected_of(snapshot):
    """What `require_unchanged` compares: the snapshot's (node, mode, bytes), or None."""
    return None if snapshot is None else snapshot.identity + (snapshot.data,)


def make_folder(workspace_folder, name, made):
    """A descriptor on the output folder `name`, made when missing, never through a symlink."""
    try:
        os.mkdir(name, dir_fd=workspace_folder)
        made.append(name)
    except FileExistsError:
        pass
    return os.open(name, FOLDER_FLAGS, dir_fd=workspace_folder)


def write_plan(workspace, plan, out):
    """W3a: temps, pending manifests, replace every target, then the final manifests."""
    writes = [target for target in plan.targets if target.changes]
    if not writes and plan.manifest_text == plan.manifest_data and plan.state_text == plan.state_data:
        out.write("no changes\n")
        return EX_DONE
    folders = {}
    try:
        return write_through(workspace, plan, writes, folders, out)
    finally:
        for handle in folders.values():
            os.close(handle)


def write_through(workspace, plan, writes, folders, out):
    """write_plan's body: every file is written through a folder descriptor in `folders`."""
    made = []
    temps = []
    state_folder, state_name = os.path.split(plan.state_rel)

    def undo():
        remove_leftover_temps(workspace)
        for name in reversed(made):
            try:
                os.rmdir(name, dir_fd=folders[""])
            except OSError:
                pass  # it holds a file already written (a pending record): it stays

    try:
        folders[""] = open_folder(workspace, "")
        for target in writes:
            folder, name = os.path.split(target.rel)
            if folder not in folders:
                folders[folder] = make_folder(folders[""], folder, made)
            temp, _ = write_temp(folders[folder], name, target.render, target.mode)
            temps.append((temp, target))
        if state_folder not in folders:
            folders[state_folder] = make_folder(folders[""], state_folder, made)
        # A writer that changed a target since the plan was made loses nothing:
        # every target must still be the file, bytes, identity and mode, the
        # plan read. A target that is no longer a regular file is refused by
        # the reader (scan.NotRegular, an Unverifiable) and undone here too.
        changed = [target.rel for target in plan.targets
                   if not same_snapshot(read_snapshot(workspace, target.rel), target.snapshot)]
    except (OSError, scan.Unverifiable) as exc:
        if "" in folders:
            undo()
        out.write("REFUSED  could not write: %s; nothing written\n" % exc)
        return EX_REFUSED
    if changed:
        undo()
        out.write("REFUSED  %s changed during the run; %s\n" % (", ".join(changed), PLAN_CHANGED))
        return EX_REFUSED
    manifest_now = expected_of(plan.manifest_snapshot)
    state_now = expected_of(plan.state_snapshot)
    try:
        if writes:
            manifest_now = write_atomic(folders[""], MANIFEST_NAME, plan.pending_manifest,
                                        manifest_now)
            state_now = write_atomic(folders[state_folder], state_name, plan.pending_state,
                                     state_now, plan.state_rel)
        for temp, target in temps:
            folder, name = os.path.split(target.rel)
            require_unchanged(folders[folder], name, expected_of(target.snapshot), target.rel)
            os.replace(temp, name, src_dir_fd=folders[folder], dst_dir_fd=folders[folder])
            out.write("wrote  %s\n" % target.rel)
        write_atomic(folders[""], MANIFEST_NAME, plan.manifest_text, manifest_now)
        write_atomic(folders[state_folder], state_name, plan.state_text, state_now,
                     plan.state_rel)
    except OSError as exc:
        undo()
        out.write("UNKNOWN  the write stopped part way: %s; rerun gen to finish it\n" % exc)
        return EX_UNKNOWN
    out.write("recorded %s and %s\n" % (MANIFEST_NAME, plan.state_rel))
    return EX_DONE


def main(workspace, host=None, adopt=False, write=False, expect=None, out=None):
    out = sys.stdout if out is None else out
    out.write("== workspace gen ==\n")
    try:
        plan = make_plan(workspace, host, adopt)
    except scan.NotRegular as exc:
        out.write("REFUSED  %s\n" % exc)
        out.write("nothing written\n")
        return EX_REFUSED
    except scan.Unverifiable as exc:
        out.write("UNKNOWN  %s\n" % exc)
        return EX_UNKNOWN
    except Refusal as refusal:
        for reason in refusal.reasons:
            out.write("REFUSED  %s\n" % reason)
        out.write("nothing written\n")
        return EX_REFUSED
    except Exception as exc:  # fail closed: never write after a crash
        out.write("UNKNOWN  gen failed: %s: %s\n" % (type(exc).__name__, exc))
        return EX_UNKNOWN
    out.write("host `%s`\n" % plan.host)
    if not write:
        for line in plan.lines:
            out.write(line + "\n")
        out.write("plan sha256=%s\n" % plan.digest)
        out.write("nothing written; to write this plan, rerun with --write --expect %s\n"
                  % plan.digest)
        return EX_DONE
    if expect != plan.digest:
        out.write("REFUSED  %s\n" % PLAN_CHANGED)
        return EX_REFUSED
    remove_leftover_temps(workspace)
    return write_plan(workspace, plan, out)
