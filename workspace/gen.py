def uses_of(document, name):
    seen = []
    for edge in document.get("edges") or []:
        if edge.get("from") == name:
            item = "%s (%s)" % (edge.get("to"), edge.get("kind"))
            if item not in seen:
                seen.append(item)
    return seen


def own_line(document, project):
    parts = []
    one_liner = project.get("one_liner")
    if one_liner:
        parts.append(one_liner)
    parts.append("lifecycle: %s." % project.get("lifecycle"))
    if project.get("owned_or_reference") != "reference":
        uses = uses_of(document, project["name"])
        if uses:
            parts.append("uses: " + ", ".join(uses))
    return "- `%s`: %s" % (project["name"], " ".join(parts))


def render_map(document, clusters, keep):
    projects = document.get("projects") or []
    system = document.get("system")
    title = "# %s workspace map" % system if isinstance(system, str) and system else "# Workspace map"
    out = [HEADER + "\n", "\n", title + "\n", "\n", INTRO, "\n",
           keep_section("top", keep.get("top", "")), "\n", "## Repos by cluster\n"]

    def section(heading, members):
        lines = []
        archived = []
        for project, first in members:
            if project.get("lifecycle") == "archived":
                if first:
                    archived.append(project["name"])
                continue
            if first:
                lines.append(own_line(document, project))
            else:
                ids = cluster_ids(project.get("cluster"))
                lines.append("- `%s`: see %s." % (project["name"],
                                                   cluster_name(clusters[ids[0]])))
        if archived:
            lines.append("Archived: %s." % ", ".join("`%s`" % name for name in archived))
        return [heading] + lines

    for cluster_id, cluster in clusters.items():
        members = []
        for project in projects:
            ids = cluster_ids(project.get("cluster")) or []
            if cluster_id in ids:
                members.append((project, ids[0] == cluster_id))
        name = cluster_name(cluster)
        one_liner = cluster.get("one_liner")
        if cluster.get("lifecycle") == "archived":
            names = [project["name"] for project, first in members if first]
            listed = ", ".join("`%s`" % item for item in names) if names else "none"
            line = "**%s** (lifecycle: archived): %s." % (name, listed)
            if one_liner:
                line += " " + one_liner
            out.extend(["\n", line + "\n"])
            continue
        heading = "**%s**" % name
        if one_liner:
            heading += " — " + one_liner
        out.append("\n")
        out.extend(line + "\n" for line in section(heading, members))

    other = [(project, True) for project in projects if not cluster_ids(project.get("cluster"))]
    if other:
        out.append("\n")
        out.extend(line + "\n" for line in section("**Other**", other))
    out.extend(["\n", CHANGING, "\n", keep_section("bottom", keep.get("bottom", ""))])
    return "".join(out)


def import_tokens(text):
    """Every `@path` import token: `@` at line start or after whitespace, outside a code span."""
    for line in text.splitlines():
        masked = []
        inside = False
        for character in line:
            if character == "`":
                inside = not inside
                masked.append(False)
            else:
                masked.append(inside)
        for index, character in enumerate(line):
            if character != "@" or masked[index]:
                continue
            if index and not line[index - 1].isspace():
                continue
            end = index + 1
            while end < len(line) and not line[end].isspace() and line[end] != "`":
                end += 1
            if end > index + 1:
                yield line[index + 1:end]


def import_gate(text, document, workspace):
    """Refuse an `@` import that resolves inside a registered project's path on any host."""
    base = os.path.abspath(workspace)
    projects = []
    for project in document.get("projects") or []:
        for path in (project.get("paths") or {}).values():
            projects.append((scan.expand_path(path, "project `%s` path" % project["name"]),
                             project["name"]))
    reasons = []
    for token in import_tokens(text):
        try:
            if token.startswith("~"):
                resolved = scan.expand_path(token, "import")
            else:
                resolved = os.path.normpath(os.path.join(base, token))
        except scan.Unverifiable:
            continue
        for path, name in projects:
            if scan.within(resolved, path):
                reasons.append("the map imports @%s, which resolves inside project `%s`; the map "
                               "must stay lazy" % (token, name))
                break
    if reasons:
        raise Refusal(*reasons)


def budget_gate(text):
    size = len(text.encode("utf-8"))
    if size > MAP_BUDGET_BYTES:
        raise Refusal("AGENTS.md would be %d bytes, over the limit of %d bytes"
                      % (size, MAP_BUDGET_BYTES))


