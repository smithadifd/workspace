class Refusal(Exception):
    """gen refuses: exit 1, nothing written. Each argument is one printed reason."""

    def __init__(self, *reasons):
        Exception.__init__(self, "; ".join(reasons))
        self.reasons = reasons


def sha256(data):
    if isinstance(data, str):
        data = data.encode("utf-8")
    return hashlib.sha256(data).hexdigest()


def plan_digest(verb, flags, files):
    """The plan hash: every flag except --write and --expect, and every planned file's bytes."""
    digest = hashlib.sha256()
    digest.update(("workspace %s plan v1\n" % verb).encode("utf-8"))
    for name, value in flags:
        digest.update(("%s=%r\n" % (name, value)).encode("utf-8"))
    for rel in sorted(files):
        data = files[rel]
        digest.update(("%s\n%d\n" % (rel, -1 if data is None else len(data))).encode("utf-8"))
        if data is not None:
            digest.update(data)
    return digest.hexdigest()


def unified(old, new, rel):
    old_lines = [] if old is None else old.splitlines(keepends=True)
    new_lines = new.splitlines(keepends=True)
    before = "/dev/null" if old is None else "a/" + rel
    lines = difflib.unified_diff(old_lines, new_lines, before, "b/" + rel)
    return "".join(line if line.endswith("\n") else line + "\n\\ No newline at end of file\n"
                   for line in lines)


def open_folder(workspace, rel):
    """A descriptor on the folder `rel` of the workspace ("" for the workspace itself).

    Each step below the workspace is opened without following a symlink, so a
    symlinked `.claude` or `state` fails here and is never read or written through.
    """
    handle = os.open(workspace, WORKSPACE_FLAGS)
    for part in [part for part in rel.split(os.sep) if part]:
        try:
            child = os.open(part, FOLDER_FLAGS, dir_fd=handle)
        finally:
            os.close(handle)
        handle = child
    return handle


def read_snapshot(workspace, rel):
    """The `scan.Snapshot` of the workspace file `rel`, or None when it does not exist.

    Its folder is opened step by step without following a symlink, and the
    file through `scan.snapshot_at`: one O_NOFOLLOW, O_NONBLOCK descriptor
    that must be a regular file (`scan.NotRegular` otherwise).
    """
    folder, name = os.path.split(rel)
    try:
        handle = open_folder(workspace, folder)
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise scan.Unverifiable("could not read %s: %s" % (rel, exc))
    try:
        return scan.snapshot_at(handle, name, rel)
    finally:
        os.close(handle)


def read_bytes(workspace, rel):
    """The bytes of the workspace file `rel`, or None when it does not exist."""
    snapshot = read_snapshot(workspace, rel)
    return None if snapshot is None else snapshot.data


def same_snapshot(now, then):
    """Whether two reads saw the same file: both absent, or equal bytes, identity and mode."""
    if now is None or then is None:
        return now is then
    return now.data == then.data and now.identity == then.identity


def output_folder_gate(workspace):
    """Refuse a `.claude` or `state` that is a symlink, before anything is read through it.

    The files below them, and in the workspace folder, are refused the same way
    when one is not a regular file, by the reader (`read_snapshot`).
    """
    reasons = []
    for name in OUTPUT_FOLDERS:
        try:
            info = os.lstat(os.path.join(workspace, name))
        except FileNotFoundError:
            continue
        except OSError as exc:
            raise scan.Unverifiable("could not read %s: %s" % (name, exc))
        if stat.S_ISLNK(info.st_mode):
            reasons.append(OUTPUT_LINK % name)
    if reasons:
        raise Refusal(*reasons)


def decode(data, label):
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise scan.Unverifiable("%s is not UTF-8: %s" % (label, exc))


def load_json(data, label):
    try:
        value = json.loads(decode(data, label))
    except ValueError as exc:
        raise scan.Unverifiable("%s is not parseable JSON: %s" % (label, exc))
    if not isinstance(value, dict):
        raise scan.Unverifiable("%s root is not an object" % label)
    return value


