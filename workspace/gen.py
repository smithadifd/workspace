def stripped_base(path):
    """The excluded path without a trailing `/**` or `/`, as `check.exclusion_forms` strips it."""
    return path[:-3] if path.endswith("/**") else path.rstrip("/")


def deny_rules(path):
    """The deny rules gen writes for one excluded path, Read before Edit."""
    base = stripped_base(path)
    rules = []
    if any(character in base for character in GLOB_CHARACTERS):
        whole = check.permission_form(base)
        rules += ["Read(%s)" % whole, "Edit(%s)" % whole]
    beneath = check.permission_form(base + "/**")
    rules += ["Read(%s)" % beneath, "Edit(%s)" % beneath]
    return rules


def covering_rules(path):
    return {"%s(%s)" % (verb, form)
            for form in check.permission_forms(path) for verb in ("Read", "Edit")}


def missing_rules(path, deny):
    """The rules to add for `path`, one rule at a time.

    A glob base needs both of its pairs by exact text; a literal base needs a
    Read and an Edit rule that `check` accepts, in any of its forms.
    """
    wanted = deny_rules(path)
    if any(character in stripped_base(path) for character in GLOB_CHARACTERS):
        return [rule for rule in wanted if rule not in deny]
    out = []
    forms = check.permission_forms(path)
    for verb, rule in (("Read", wanted[0]), ("Edit", wanted[1])):
        if not any(item == "%s(%s)" % (verb, form) for form in forms for item in deny):
            out.append(rule)
    return out


def code_root_texts(code_roots):
    roots = []
    for root in code_roots.values():
        if root not in roots:
            roots.append(root)
    return roots


def empty_owned():
    return {"additionalDirectories": [], "deny": [], "denyRead": []}


def settings_lists(settings, create):
    """The three lists gen owns entries in, refusing a shape it cannot merge into."""
    permissions = settings.get("permissions")
    if permissions is None and create:
        permissions = settings["permissions"] = {}
    if permissions is not None and not isinstance(permissions, dict):
        raise Refusal("settings.json `permissions` is not an object; gen cannot merge into it")
    lists = {}
    for key in ("additionalDirectories", "deny"):
        value = None if permissions is None else permissions.get(key)
        if value is not None and not isinstance(value, list):
            raise Refusal("settings.json `permissions.%s` is not a list" % key)
        lists[key] = value
    sandbox = settings.get("sandbox")
    lists["denyRead"] = None
    if "sandbox" in settings:
        if not isinstance(sandbox, dict):
            raise Refusal("settings.json `sandbox` is not an object; gen cannot merge into it")
        filesystem = sandbox.get("filesystem")
        if filesystem is not None and not isinstance(filesystem, dict):
            raise Refusal("settings.json `sandbox.filesystem` is not an object")
        value = None if filesystem is None else filesystem.get("denyRead")
        if value is not None and not isinstance(value, list):
            raise Refusal("settings.json `sandbox.filesystem.denyRead` is not a list")
        lists["denyRead"] = value
    return lists


def hook_entry():
    """The one SessionStart entry gen may own."""
    return {"hooks": [{"type": "command", "command": HOOK_COMMAND}]}


def hook_list(settings, create):
    """`hooks.SessionStart` in the settings; None when absent and not `create`.

    It refuses a shape gen cannot merge into. gen calls it only when it must
    add or remove its own entry, so a hooks block gen has no part in is never
    judged and passes through as it is.
    """
    hooks = settings.get("hooks")
    if hooks is None:
        if not create:
            return None
        hooks = settings["hooks"] = {}
    if not isinstance(hooks, dict):
        raise Refusal("settings.json `hooks` is not an object; gen cannot merge into it")
    events = hooks.get(HOOK_EVENT)
    if events is None:
        if not create:
            return None
        events = hooks[HOOK_EVENT] = []
    if not isinstance(events, list):
        raise Refusal("settings.json `hooks.%s` is not a list; gen cannot merge into it"
                      % HOOK_EVENT)
    return events


def hook_present(settings, owned):
    """[HOOK_COMMAND] when gen owns its entry and the settings hold it, else []."""
    if HOOK_COMMAND not in (owned.get(HOOK_KEY) or []):
        return []
    try:
        events = hook_list(settings, create=False)
    except Refusal:
        return []
    return [HOOK_COMMAND] if events is not None and hook_entry() in events else []


def runs_prompt(event):
    """True when a SessionStart entry has a command hook whose command is exactly HOOK_COMMAND."""
    hooks = event.get("hooks") if isinstance(event, dict) else None
    if not isinstance(hooks, list):
        return False
    return any(isinstance(hook, dict) and hook.get("type") == "command"
               and hook.get("command") == HOOK_COMMAND for hook in hooks)


def merge_hook(merged, wanted, owned):
    """Add or remove gen's one SessionStart entry in `merged`; return what gen owns after.

    On: an entry equal to gen's is gen's only when the manifest already records
    owning it; adopting never claims one. Otherwise, when the manifest records no
    ownership and any entry already runs `workspace prompt` (`runs_prompt`), the
    person wrote it: gen adds nothing and owns nothing. When the manifest does
    record ownership and gen's exact entry is gone (edited or removed), gen
    appends it, so the settings no longer match the record and the run refuses
    as a hand edit; ownership is never dropped silently. Otherwise gen appends
    its entry and owns it. Off: remove one
    equal entry, only when the manifest records gen owning it; a `SessionStart`
    list or `hooks` object that removal leaves empty goes too. Nothing else in
    `hooks` is changed.
    """
    owns = HOOK_COMMAND in owned
    entry = hook_entry()
    if wanted:
        events = hook_list(merged, create=False) or []
        if owns and entry in events:
            return [HOOK_COMMAND]
        if not owns and any(runs_prompt(event) for event in events):
            return []
        hook_list(merged, create=True).append(entry)
        return [HOOK_COMMAND]
    if not owns:
        return []
    events = hook_list(merged, create=False)
    if events is not None and entry in events:
        events.remove(entry)
        if not events:
            del merged["hooks"][HOOK_EVENT]
            if not merged["hooks"]:
                del merged["hooks"]
    return []


def ensure_list(settings, key):
    if key == "denyRead":
        filesystem = settings["sandbox"].setdefault("filesystem", {})
        return filesystem.setdefault("denyRead", [])
    return settings.setdefault("permissions", {}).setdefault(key, [])


def merge_settings(existing, code_roots, excluded, owned, adopting, session_prompt=False):
    """Merge gen's entries into the settings; return (merged, owned after the merge).

    `owned` is what the manifest records gen owns. When `adopting`, every
    existing entry that covers a registry path is recorded as gen-owned too.
    `session_prompt` is whether the registry turns the SessionStart hook on.
    """
    merged = copy.deepcopy(existing)
    lists = settings_lists(merged, create=False)
    sandbox_declared = "sandbox" in merged
    hook_owned = list(owned.get(HOOK_KEY) or [])
    owned = {key: list(owned.get(key, [])) for key in empty_owned()}
    roots = code_root_texts(code_roots)
    covering = set()
    for path in excluded:
        covering |= covering_rules(path)
    sandboxed = set()
    for path in excluded:
        sandboxed |= check.sandbox_forms(path)
    keeps = {"additionalDirectories": set(roots), "deny": covering, "denyRead": sandboxed}

    if adopting:
        for key, current in lists.items():
            for item in current or []:
                if item in keeps[key] and item not in owned[key]:
                    owned[key].append(item)

    # S3: remove only what gen recorded owning whose source left the registry.
    for key, current in lists.items():
        gone = [item for item in owned[key] if item not in keeps[key]]
        if gone and current is not None:
            current[:] = [item for item in current if item not in gone]
        owned[key] = [item for item in owned[key] if item not in gone]

    def add(key, item):
        ensure_list(merged, key).append(item)
        if item not in owned[key]:
            owned[key].append(item)

    for root in roots:
        if root not in (lists["additionalDirectories"] or []):
            add("additionalDirectories", root)
    for path in excluded:
        deny = merged.get("permissions", {}).get("deny") or []
        for rule in missing_rules(path, deny):
            add("deny", rule)
    if sandbox_declared:
        for path in excluded:
            current = merged["sandbox"].get("filesystem", {}).get("denyRead") or []
            if not check.denyread_covers(current, path):
                add("denyRead", path)
    result = {key: sorted(value) for key, value in owned.items()}
    hook_owned = merge_hook(merged, session_prompt, hook_owned)
    if hook_owned:
        result[HOOK_KEY] = hook_owned
    return merged, result


def settings_view(settings, owned):
    """The gen-owned part of the settings: each owned entry still present, as canonical JSON."""
    if settings is None:
        return None
    try:
        lists = settings_lists(settings, create=False)
    except Refusal:
        lists = {key: None for key in empty_owned()}
    view = {}
    for key in empty_owned():
        current = lists.get(key) or []
        view[key] = sorted(item for item in owned.get(key, []) if item in current)
    if owned.get(HOOK_KEY):  # absent unless gen owns the hook, so older records hash the same
        view[HOOK_KEY] = hook_present(settings, owned)
    return json.dumps(view, sort_keys=True)


def settings_plan_lines(before, after):
    lines = []
    for key in list(empty_owned()) + [HOOK_KEY]:
        old = before.get(key, [])
        new = after.get(key, [])
        for item in old:
            if item not in new:
                lines.append("-  %s: %s" % (key, item))
        for item in new:
            if item not in old:
                lines.append("+  %s: %s" % (key, item))
    return lines


def settings_text(settings):
    return json.dumps(settings, indent=2, ensure_ascii=False) + "\n"


